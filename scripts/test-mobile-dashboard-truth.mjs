import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source=fs.readFileSync('apps/mobile/index.js','utf8');
const dashboard=source.slice(source.indexOf('function DashboardScreen('),source.indexOf('function PlaceholderTab('));
let statsState={stats:null,loading:false,error:'Unavailable'};
const React={createElement:(type,props,...children)=>({type,props:props??{},children}),Fragment:'Fragment'};
const context={React,useProfile:()=>({}),useVaultStats:()=>statsState,styles:new Proxy({},{get:()=>({})}),NAVY:'navy',ScrollView:'ScrollView',View:'View',Text:'Text',Pressable:'Pressable',Ionicons:'Ionicons',MedicalIdCardMobile:'MedicalIdCardMobile',StatCard:'StatCard'};
vm.createContext(context);
vm.runInContext(ts.transpileModule(dashboard,{compilerOptions:{jsx:ts.JsxEmit.React,module:ts.ModuleKind.CommonJS}}).outputText+'\nthis.render=DashboardScreen;',context);
const flatten=node=>!node||typeof node!=='object'?[]:[node,...(node.children??[]).flat(Infinity).flatMap(flatten)];
const routes=[];
let tree=flatten(context.render({onNavigate:r=>routes.push(r)}));
let cards=tree.filter(n=>n.type==='StatCard');
assert.equal(cards.find(n=>n.props.title==='Health Records').props.value,'—');
for(const title of ['Appointments','Medications'])assert.equal(cards.find(n=>n.props.title===title).props.value,'—');
const buttons=tree.filter(n=>n.type==='Pressable');
assert.equal(buttons.length,3);
buttons.forEach(n=>{assert.equal(n.props.accessibilityRole,'button');n.props.onPress();});
assert.deepEqual(routes,['medical','care','records']);
assert.ok(!JSON.stringify(tree).includes('Annual Physical Examination'));
statsState={stats:{totalRecords:3,connectedProviders:1},loading:false,error:null};
tree=flatten(context.render({onNavigate:()=>{}}));
assert.equal(tree.find(n=>n.type==='StatCard'&&n.props.title==='Health Records').props.value,'3');
assert.ok(source.includes('onNavigate={setActiveRoute}'));
console.log('PASS dashboard: unavailable counts, real record count, accessible working routes, no sample activity');
