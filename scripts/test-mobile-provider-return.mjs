import assert from 'node:assert/strict';
import {watchProviderReturn} from '../apps/mobile/src/lib/provider-return.js';
let listener,removed=0,checks=0,failures=0,finish;
const appState={currentState:'active',addEventListener(event,callback){assert.equal(event,'change');listener=callback;return {remove(){removed++;}};}};
const stop=watchProviderReturn({appState,check:async()=>{checks++;await new Promise(resolve=>{finish=resolve;});},onError:()=>failures++});
await listener('active');assert.equal(checks,0);
await listener('background');const first=listener('active');assert.equal(checks,1);
await listener('inactive');await listener('active');assert.equal(checks,1,'No overlapping verification');
finish();await first;
await listener('active');assert.equal(checks,1,'Duplicate active event is not a return');
await listener('inactive');const second=listener('active');assert.equal(checks,2);
finish();await second;stop();assert.equal(removed,1);
await listener('background');await listener('active');assert.equal(checks,2);
const stopError=watchProviderReturn({appState,check:async()=>{throw Error('offline');},onError:()=>failures++});
await listener('background');await listener('active');assert.equal(failures,1);
await listener('background');await listener('active');assert.equal(failures,2,'Can retry after failure');stopError();
let reject;
const stopPending=watchProviderReturn({appState,check:()=>new Promise((_,r)=>{reject=r;}),onError:()=>failures++});
await listener('inactive');const pending=listener('active');stopPending();reject(Error('late'));await pending;assert.equal(failures,2,'No late error after unmount');
console.log('PASS provider return transitions, overlap prevention, retry and unmount cleanup');
