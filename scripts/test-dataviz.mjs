import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const tokens=JSON.parse(fs.readFileSync('packages/design-tokens/dataviz.json','utf8'));
let source=fs.readFileSync('src/components/charts/chartPolicy.ts','utf8').replace("import tokens from '../../../packages/design-tokens/dataviz.json';",`const tokens=${JSON.stringify(tokens)};`);
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const policy=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
assert.equal(tokens.series.length,12);
for(const s of tokens.series)assert.equal(Object.keys(s.steps).length,11);
assert.deepEqual(policy.chartOrder,'harbor brass rose orchid jade indigo olive fern lapis ember slate clay'.split(' '));
assert.equal(policy.seriesValues('light')[0],'var(--data-01-harbor-60)');
assert.equal(policy.seriesValues('dark')[0],'var(--data-01-harbor-50)');
assert.ok(policy.needsEncoding(['brass','olive']));assert.ok(policy.needsEncoding(['indigo','lapis']));
assert.ok(policy.needsEncoding(policy.chartOrder.slice(0,5)));assert.equal(policy.needsEncoding(['harbor','rose']),false);
for(const timing of Object.values(policy.chartMotion(true)))assert.equal(timing.ms,0);
for(const timing of Object.values(policy.chartMotion(false,301)))assert.equal(timing.ms,0);
assert.ok(policy.seriesDelay(11)+policy.chartMotion(false).enter.ms<=1000);
assert.equal(policy.seriesDelay(2,true),0);
assert.equal(policy.highchartsTheme('light').colors.length,12);
assert.equal(policy.powerBiTheme('dark').good,tokens.status.positive[1]);
assert.equal(tokens.seed.length,12);assert.ok(tokens.seed.every(row=>row.length===8));
assert.ok(!/#[0-9a-f]{6}/i.test(fs.readFileSync('src/components/charts/TrendChart.tsx','utf8')));
console.log('PASS chart ramps, ordered steps, restricted pairs, encoding threshold, seed, motion caps/reduction and export themes');
