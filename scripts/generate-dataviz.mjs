import {readFileSync,writeFileSync} from 'node:fs';
const data=JSON.parse(readFileSync(new URL('../packages/design-tokens/dataviz.json',import.meta.url)));
let css='/* Generated by scripts/generate-dataviz.mjs. */\n:root {\n';
for(const s of data.series)for(const [step,value] of Object.entries(s.steps))css+=` --${s.token}-${step}: ${value};\n`;
for(const [group,prefix] of [['theme','chart'],['signal','hv-signal'],['ai','ai']])for(const [role,modes] of Object.entries(data[group]))for(const [mode,value] of Object.entries(modes))css+=` --${prefix}-${role}-${mode}: ${value};\n`;
for(const [key,t] of Object.entries(data.motion))css+=` --motion-chart-${key}: ${t.ms}ms;\n`;
for(const [key,pair] of Object.entries(data.status))pair.forEach((v,i)=>css+=` --chart-status-${key}-${i?'dark':'light'}: ${v};\n`);
data.diverging.forEach((v,i)=>css+=` --chart-diverging-${i+1}: ${v};\n`);
css+='}\n';
for(const mode of ['light','dark']){
 css+=`${mode==='light'?':root, [data-chart-mode="light"]':'[data-theme="dark"], [data-chart-mode="dark"]'} {\n`;
 for(const role of Object.keys(data.theme))css+=` --chart-${role}: var(--chart-${role}-${mode});\n`;
 for(const [i,key] of data.order.entries()){
  const s=data.series.find(s=>s.key===key),step=s[mode==='light'?'chartLight':'chartDark'];
  css+=` --hv-color-datavis-series-${i+1}: var(--${s.token}-${String(step).padStart(2,'0')});\n`;
 }
 css+='}\n';
}
css+='@media (prefers-reduced-motion: reduce) { :root {\n';
for(const key of Object.keys(data.motion))css+=` --motion-chart-${key}: 0ms;\n`;
css+='} }\n';
const url=new URL('../src/tokens/global/dataviz-option1.css',import.meta.url);
if(process.argv.includes('--check')){if(readFileSync(url,'utf8')!==css)throw new Error('Stale chart tokens');}else writeFileSync(url,css);
